// Precompiles schema/expected-points.schema.json into src/push/expected-points.validate.js with
// Ajv's standalone code, so /api/expected-points validates without code generation at run time
// (Workers forbid `new Function`) and inside the 10 ms CPU limit. Run after any schema change:
//   npm run build:validator
// test/push/validate.test.ts fails while the committed file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const root = new URL("../", import.meta.url);
export const OUTPUT = new URL("src/push/expected-points.validate.js", root);

/** The module's text. Same Ajv options as the test suite's, except only the first error is kept. */
export function generate() {
  const schema = JSON.parse(readFileSync(new URL("schema/expected-points.schema.json", root), "utf8"));
  const ajv = new Ajv2020({ strict: true, allErrors: false, code: { source: true, esm: true, lines: true } });
  addFormats.default(ajv);
  const code = standaloneCode.default(ajv, ajv.compile(schema));
  // Ajv's ESM output still pulls its runtime helpers (the date-time check, ucs2length) in with
  // require(); turn each into an import so the Function's bundle and Node's ESM both load it.
  const imports = new Map();
  const body = code.replace(/require\("([^"]+)"\)/g, (_, spec) => {
    if (!imports.has(spec)) imports.set(spec, `runtime${imports.size}`);
    return imports.get(spec);
  });
  if (/\brequire\(|new Function|\beval\(/.test(body)) throw new Error("generated validator still uses require or code generation");
  // Both helpers are CommonJS with __esModule set. Node's ESM puts module.exports on a namespace's
  // `default`; esbuild and Vite may hand over exports.default instead. Take module.exports either way.
  const head = [
    "const cjs = (ns) => (ns.default && ns.default.__esModule ? ns.default : ns);",
    ...[...imports].map(([spec, name]) => `import * as ${name}NS from "${spec}.js";\nconst ${name} = cjs(${name}NS);`),
  ].join("\n");
  return `// Generated by scripts/build_validator.mjs from schema/expected-points.schema.json. Do not edit.\n${head}\n${body}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUTPUT, generate());
  console.log(`wrote ${OUTPUT.pathname}`);
}
