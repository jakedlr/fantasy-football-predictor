"""Base Rate stats: the Scoring Stats no book offers (fumbles lost, 2-pt conversions).

Each is a Poisson from the nflverse Base Rates in `params/base_rates.json`
(research/nflverse-data.md section 4). They are sampled independently of the
copula, so `base_rate_stats` returns plain Stat Distributions to add to the ones
fitted from markets.

Assumptions:
- Fumbles lost, RB/WR/TE: Poisson(rate per touch × expected touches), touches =
  receptions + carries.
- Fumbles lost, QB: the flat per-game rate. The doc's better model (≈0.06 per
  expected sack plus rush-attempt fumbles) needs a sacks expectation and a QB
  per-carry rate, neither of which exists yet; QB FL barely varies by usage tier,
  so the flat rate is the doc's stated alternative. S4.4 replaces it.
- 2-pt conversions: a flat per-game rush+rec rate per position, split into
  rushing_2pt and receiving_2pt by the player's rushing TD share (ffp.td_share;
  the position's share when the caller passes none), since a 2-pt is scored the
  way a TD of that kind is. Thinning a Poisson gives independent
  Poissons whose rates sum to the original, so the split is exact. QBs also get
  passing_2pt at the per-game passing rate.
- Fumbles lost per touch need both receptions and carries: receptions from
  their market; carries from theirs, else from a rushing-yards mean over the
  position's `yards_per_carry` (FanDuel has no carries market), else (WR/TE)
  the carries Base Rate. Missing either (an RB with neither a carries nor a
  rushing-yards market, a WR with no receptions market), the position's flat
  per-game rate stands in, as for QBs, rather than counting the missing stat
  as 0 touches.
- Carries with no rushing market: the position's `carries_per_game` Base Rate.
  A null value (not yet generated by build_params.py) counts as 0 carries; a
  position with no entry at all (RB, QB) needs a carries or rushing-yards market.
"""

from collections.abc import Mapping

from ffp import params as _params
from ffp.distributions import Poisson

POSITIONS = ("QB", "RB", "WR", "TE")


def _check(position: str) -> None:
    if position not in POSITIONS:
        raise ValueError(f"no Base Rates for position {position!r} (known: {', '.join(POSITIONS)})")


def _load(params: Mapping | None) -> Mapping:
    return _params.load("base_rates") if params is None else params


def expected_touches(
    position: str,
    *,
    receptions_mean: float | None,
    carries_mean: float | None = None,
    params: Mapping | None = None,
) -> float:
    """Expected receptions + carries. A missing receptions mean counts as 0.

    carries_mean None (no rushing market) falls back to the position's
    `carries_per_game` Base Rate; null there counts as 0.
    """
    _check(position)
    if carries_mean is None:
        rates = _load(params).get("carries_per_game", {})
        if position not in rates:
            raise ValueError(f"no carries Base Rate for {position}: a carries market is required")
        carries_mean = rates[position] or 0.0
    return float((receptions_mean or 0.0) + carries_mean)


def fumbles_lost(position: str, expected_touches: float, params: Mapping | None = None) -> Poisson:
    """Fumbles lost: rate per touch × expected touches (RB/WR/TE), flat per game (QB)."""
    _check(position)
    if expected_touches < 0:
        raise ValueError(f"invalid expected touches {expected_touches}")
    p = _load(params)
    if position == "QB":
        return Poisson(p["fumbles_lost_per_game"]["QB"])
    return Poisson(p["fumbles_lost_per_touch"][position] * expected_touches)


def td_rushing_share(position: str, params: Mapping | None = None) -> float:
    """The share of the position's rush+rec TDs (and 2-pt conversions) scored rushing."""
    _check(position)
    return float(_load(params)["td_rushing_share"][position])


def two_point_conversions(
    position: str, params: Mapping | None = None, *, rushing_share: float | None = None
) -> dict[str, Poisson]:
    """2-pt conversions keyed by Scoring Stat; QBs also get passing_2pt.

    `rushing_share` is the player's own rushing TD share (ffp.td_share); None uses the
    position share.
    """
    _check(position)
    p = _load(params)
    rate = p["rush_rec_2pt_per_game"][position]
    if rushing_share is None:
        share = td_rushing_share(position, p)
    elif 0.0 <= rushing_share <= 1.0:
        share = float(rushing_share)
    else:
        raise ValueError(f"invalid rushing TD share {rushing_share} (must be in [0, 1])")
    out = {"rushing_2pt": Poisson(rate * share), "receiving_2pt": Poisson(rate * (1 - share))}
    if position == "QB":
        out["passing_2pt"] = Poisson(p["pass_2pt_per_game"]["QB"])
    return out


def carries_from_rushing_yards(position: str, rushing_yards_mean: float, params: Mapping | None = None) -> float | None:
    """Expected carries from a rushing-yards mean: mean / the position's `yards_per_carry`.

    None when the Base Rates have no (or a null) yards per carry for the position.
    """
    _check(position)
    ypc = _load(params).get("yards_per_carry", {}).get(position)
    if not ypc:
        return None
    return max(float(rushing_yards_mean), 0.0) / float(ypc)


def base_rate_stats(
    position: str,
    *,
    receptions_mean: float | None,
    carries_mean: float | None = None,
    params: Mapping | None = None,
    rushing_share: float | None = None,
    rushing_yards_mean: float | None = None,
) -> dict[str, Poisson]:
    """All Base Rate Stat Distributions for one player, keyed by Scoring Stat.

    `rushing_share` splits the 2-pt rate as in `two_point_conversions`. With no
    `carries_mean` (no carries market), a `rushing_yards_mean` sets expected
    carries through `carries_from_rushing_yards`.
    """
    _check(position)
    p = _load(params)
    if carries_mean is None and rushing_yards_mean is not None:
        carries_mean = carries_from_rushing_yards(position, rushing_yards_mean, p)
    carries_known = carries_mean is not None or position in p.get("carries_per_game", {})
    if position == "QB" or receptions_mean is None or not carries_known:
        # QB fumbles don't depend on touches (S4.4 dropped); with a usage mean missing, the per-game rate.
        fumbles = Poisson(p["fumbles_lost_per_game"][position])
    else:
        touches = expected_touches(position, receptions_mean=receptions_mean, carries_mean=carries_mean, params=p)
        fumbles = fumbles_lost(position, touches, p)
    return {"fumbles_lost": fumbles, **two_point_conversions(position, p, rushing_share=rushing_share)}
